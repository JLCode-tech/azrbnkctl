// Package state manages the IDs cache file (.azrbnkctl/<cluster>/state.env).
package state

import (
	"bufio"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"
)

// State holds the IDs and discovered network attributes for a single cluster.
type State struct {
	dir      string
	data     map[string]string
	readOnly bool
}

// New creates an empty State object for dir.
func New(dir string) (*State, error) {
	return &State{dir: dir, data: make(map[string]string)}, nil
}

// Load reads the state.env file from dir. If the file does not exist, Load
// returns an empty State (normal on first run).
func Load(dir string) (*State, error) {
	s := &State{dir: dir, data: make(map[string]string)}

	path := s.path()
	// #nosec G304 -- path is derived from operator-supplied state dir (.azrbnkctl/<cluster>)
	f, err := os.Open(path)
	if os.IsNotExist(err) {
		return s, nil
	}
	if err != nil {
		return nil, fmt.Errorf("opening state %s: %w", path, err)
	}
	defer f.Close()

	scanner := bufio.NewScanner(f)
	lineNum := 0
	for scanner.Scan() {
		lineNum++
		line := strings.TrimSpace(scanner.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		idx := strings.IndexByte(line, '=')
		if idx < 1 {
			return nil, fmt.Errorf("state %s line %d: expected KEY=VALUE, got %q", path, lineNum, line)
		}
		key := line[:idx]
		val := line[idx+1:]
		s.data[key] = val
	}
	if err := scanner.Err(); err != nil {
		return nil, fmt.Errorf("reading state %s: %w", path, err)
	}
	return s, nil
}

// Get returns the value for key, or "" if not present.
func (s *State) Get(key string) string {
	return s.data[key]
}

// Set stores key=value in memory. Call Save to persist.
func (s *State) Set(key, value string) {
	s.data[key] = value
}

// Delete removes key from the state. Call Save to persist.
func (s *State) Delete(key string) {
	delete(s.data, key)
}

// MarkReadOnly puts the State into read-only mode for dry-run.
func (s *State) MarkReadOnly() {
	s.readOnly = true
}

// ReadOnly reports whether Save is currently a no-op.
func (s *State) ReadOnly() bool {
	return s.readOnly
}

// Save writes the in-memory state to state.env atomically.
func (s *State) Save() error {
	if s.readOnly {
		return nil
	}
	if err := os.MkdirAll(s.dir, 0o750); err != nil {
		return fmt.Errorf("mkdir %s: %w", s.dir, err)
	}

	tmp := s.path() + ".tmp"
	// #nosec G304 -- tmp path inside state directory
	f, err := os.Create(tmp)
	if err != nil {
		return fmt.Errorf("creating temp state: %w", err)
	}

	fmt.Fprintf(f, "# Generated by azrbnkctl on %s — do not edit by hand\n",
		time.Now().UTC().Format(time.RFC3339))
	keys := make([]string, 0, len(s.data))
	for k := range s.data {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		fmt.Fprintf(f, "%s=%s\n", k, s.data[k])
	}

	if err := f.Close(); err != nil {
		_ = os.Remove(tmp)
		return fmt.Errorf("closing temp state: %w", err)
	}
	if err := os.Rename(tmp, s.path()); err != nil {
		_ = os.Remove(tmp)
		return fmt.Errorf("renaming state file: %w", err)
	}
	return nil
}

func (s *State) path() string {
	return filepath.Join(s.dir, "state.env")
}

// Dir returns the state directory.
func (s *State) Dir() string { return s.dir }

// KubeconfigPath returns the path where kubeconfig is saved for this cluster.
func (s *State) KubeconfigPath() string {
	if custom := s.Get("KUBECONFIG_PATH"); custom != "" {
		return custom
	}
	return filepath.Join(s.dir, "kubeconfig")
}
