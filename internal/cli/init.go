package cli

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/spf13/cobra"
	"gopkg.in/yaml.v3"

	"github.com/JLCode-tech/azrbnkctl/internal/intent"
)

var (
	flagInitSubscription string
	flagInitName         string
	flagInitLocation     string
	flagInitPattern      string
	flagInitVNetCIDR     string
	flagInitExtCIDR      string
	flagInitIntCIDR      string
	flagInitForce        bool
)

var initCmd = &cobra.Command{
	Use:   "init [directory]",
	Short: "Scaffold a new azrbnkctl cluster workspace (cluster.yaml, keys/, artifacts/, AGENTS.md)",
	Long: `azrbnkctl init creates a new deployment workspace ready for provisioning:
  - cluster.yaml (declarative cluster specification)
  - keys/ (gitignored directory for license.jwt and FAR auth archive)
  - artifacts/ (workspace output directory for kubeconfig and reports)
  - AGENTS.md (quick-start reference for AI agents and operators)
  - .env (local environment file)

Example:
  azrbnkctl init poc-aks --subscription-id 00000000-0000-0000-0000-000000000000 --name bnk-cluster-01
  azrbnkctl init . --subscription-id 00000000-0000-0000-0000-000000000000`,
	Args: cobra.MaximumNArgs(1),
	RunE: runInit,
}

func init() {
	initCmd.Flags().StringVar(&flagInitSubscription, "subscription-id", "", "Azure Subscription ID (required)")
	initCmd.Flags().StringVar(&flagInitName, "name", "", "Cluster name (default: directory name)")
	initCmd.Flags().StringVar(&flagInitLocation, "location", "eastus2", "Azure region/location")
	initCmd.Flags().StringVar(&flagInitPattern, "pattern", "dual-interface", "Topology pattern (dual-interface or external-only)")
	initCmd.Flags().StringVar(&flagInitVNetCIDR, "vnet-cidr", "10.0.0.0/16", "VNet address space CIDR")
	initCmd.Flags().StringVar(&flagInitExtCIDR, "ext-cidr", "10.0.17.0/24", "External dataplane subnet CIDR")
	initCmd.Flags().StringVar(&flagInitIntCIDR, "int-cidr", "10.0.18.0/24", "Internal dataplane subnet CIDR")
	initCmd.Flags().BoolVarP(&flagInitForce, "force", "f", false, "Overwrite existing files if present")

	rootCmd.AddCommand(initCmd)
}

func runInit(_ *cobra.Command, args []string) error {
	targetDir := "."
	if len(args) > 0 {
		targetDir = args[0]
	}

	absDir, err := filepath.Abs(targetDir)
	if err != nil {
		return fmt.Errorf("resolve target dir: %w", err)
	}

	dirName := filepath.Base(absDir)
	clusterName := flagInitName
	if clusterName == "" {
		if dirName == "." || dirName == "/" {
			clusterName = "bnk-aks"
		} else {
			clusterName = sanitizeName(dirName)
		}
	}

	subID := flagInitSubscription
	if subID == "" {
		subID = "YOUR_AZURE_SUBSCRIPTION_ID"
	}

	if err := os.MkdirAll(absDir, 0o750); err != nil {
		return fmt.Errorf("create workspace directory: %w", err)
	}

	// 1. Write cluster.yaml
	clusterFile := filepath.Join(absDir, "cluster.yaml")
	if !flagInitForce && fileExists(clusterFile) {
		return fmt.Errorf("%s already exists (pass -f / --force to overwrite)", clusterFile)
	}

	clusterConfig := intent.Cluster{
		APIVersion: intent.APIVersion,
		Kind:       intent.Kind,
		Metadata: intent.Metadata{
			Name:           clusterName,
			SubscriptionID: subID,
			Location:       flagInitLocation,
		},
		Pattern: flagInitPattern,
		Network: intent.Network{
			VNetCIDR: flagInitVNetCIDR,
			Subnets: intent.SubnetsSpec{
				System:   "10.0.0.0/20",
				Public:   "10.0.16.0/24",
				External: flagInitExtCIDR,
				Internal: flagInitIntCIDR,
			},
		},
		ClusterSpec: intent.ClusterSpec{
			KubernetesVersion: "1.32.0",
			SystemNodePool: intent.NodePoolSpec{
				Name:   "system",
				VMSize: "Standard_D4s_v5",
				Count:  2,
			},
			TMMNodePool: intent.NodePoolSpec{
				Name:   "tmm",
				VMSize: "Standard_D8s_v5",
				Count:  1,
			},
		},
		Bnk: intent.BnkSpec{
			ManifestVersion: "2.4.0-3.2882.0",
			DeploymentSize:  "small",
			TmmCpu:          "2",
			TmmMemory:       "4Gi",
			TmmMtu:          1500,
			FARArchive:      "./keys/f5-far-auth-key.tgz",
			JWT:             "./keys/license.jwt",
		},
		Tags: map[string]string{
			"Environment": "PoC",
			"ManagedBy":   "azrbnkctl",
		},
	}

	yamlData, err := yaml.Marshal(&clusterConfig)
	if err != nil {
		return fmt.Errorf("marshal cluster.yaml: %w", err)
	}

	header := []byte("# Generated by azrbnkctl init\n# Edit this file to customize your Azure AKS BNK deployment.\n\n")
	if err := os.WriteFile(clusterFile, append(header, yamlData...), 0o600); err != nil {
		return fmt.Errorf("write %s: %w", clusterFile, err)
	}

	// 2. Setup keys/ directory with local .gitignore
	keysDir := filepath.Join(absDir, "keys")
	if err := os.MkdirAll(keysDir, 0o700); err != nil {
		return fmt.Errorf("create keys dir: %w", err)
	}

	keysGitignore := filepath.Join(keysDir, ".gitignore")
	gitignoreContent := "# Ignore all secret keys and auth tokens\n*\n!.gitignore\n!README.md\n"
	_ = os.WriteFile(keysGitignore, []byte(gitignoreContent), 0o600)

	keysReadme := filepath.Join(keysDir, "README.md")
	readmeContent := "# Secret Material Directory\n\n" +
		"Place your sensitive credentials here:\n" +
		"- `license.jwt`: Your F5 BNK subscription JWT license.\n" +
		"- `f5-far-auth-key.tgz`: Your F5 FAR registry auth key archive.\n\n" +
		"This directory is protected by `.gitignore` to prevent accidental commits.\n"
	_ = os.WriteFile(keysReadme, []byte(readmeContent), 0o600)

	// 3. Setup artifacts/ directory
	artifactsDir := filepath.Join(absDir, "artifacts")
	_ = os.MkdirAll(artifactsDir, 0o750)

	// 4. Write AGENTS.md guide
	agentsFile := filepath.Join(absDir, "AGENTS.md")
	agentsContent := fmt.Sprintf("# Operator & Agent Quick-Start Guide for %s\n\n"+
		"This workspace defines an F5 BIG-IP Next for Kubernetes (BNK) deployment on Azure Kubernetes Service (AKS).\n\n"+
		"## 4-Command Lifecycle\n\n"+
		"1. **Preflight Check**:\n"+
		"   ```bash\n"+
		"   azrbnkctl doctor --subscription-id %s --location %s\n"+
		"   ```\n\n"+
		"2. **Validate Configuration**:\n"+
		"   ```bash\n"+
		"   azrbnkctl validate cluster.yaml\n"+
		"   ```\n\n"+
		"3. **Deploy (Plan & Provision)**:\n"+
		"   ```bash\n"+
		"   azrbnkctl up -f cluster.yaml --dry-run\n"+
		"   azrbnkctl up -f cluster.yaml\n"+
		"   ```\n\n"+
		"4. **Connect via Kubeconfig**:\n"+
		"   ```bash\n"+
		"   azrbnkctl kubeconfig -f cluster.yaml --write-global\n"+
		"   ```\n\n"+
		"5. **Run Tests**:\n"+
		"   ```bash\n"+
		"   azrbnkctl test dns --target f5.com\n"+
		"   ```\n\n"+
		"6. **Teardown**:\n"+
		"   ```bash\n"+
		"   azrbnkctl down -f cluster.yaml\n"+
		"   ```\n", clusterName, subID, flagInitLocation)
	_ = os.WriteFile(agentsFile, []byte(agentsContent), 0o600)

	// 5. Write .env helper
	dotenvFile := filepath.Join(absDir, ".env")
	if !fileExists(dotenvFile) {
		envContent := fmt.Sprintf("# Local environment configuration\nAZURE_SUBSCRIPTION_ID=%s\n", subID)
		_ = os.WriteFile(dotenvFile, []byte(envContent), 0o600)
	}

	fmt.Fprintf(os.Stdout, "✓ Initialized azrbnkctl workspace in %s\n", absDir)
	fmt.Fprintf(os.Stdout, "  • Created cluster.yaml (cluster=%s, location=%s)\n", clusterName, flagInitLocation)
	fmt.Fprintf(os.Stdout, "  • Created keys/ (drop license.jwt and f5-far-auth-key.tgz here)\n")
	fmt.Fprintf(os.Stdout, "  • Created artifacts/ and AGENTS.md\n\n")
	fmt.Fprintf(os.Stdout, "Next steps:\n")
	fmt.Fprintf(os.Stdout, "  1. Drop your license in keys/license.jwt\n")
	fmt.Fprintf(os.Stdout, "  2. Run: azrbnkctl doctor --subscription-id %s\n", subID)
	fmt.Fprintf(os.Stdout, "  3. Run: azrbnkctl up -f %s/cluster.yaml\n", targetDir)

	return nil
}

func sanitizeName(s string) string {
	s = strings.ToLower(s)
	var b strings.Builder
	for _, r := range s {
		if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') || r == '-' {
			b.WriteRune(r)
		} else {
			b.WriteRune('-')
		}
	}
	res := strings.Trim(b.String(), "-")
	if res == "" {
		return "bnk-aks"
	}
	return res
}

func fileExists(p string) bool {
	_, err := os.Stat(p)
	return err == nil
}
